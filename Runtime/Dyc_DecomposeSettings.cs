using System;
using UnityEngine;

namespace NekoDynamicCollision
{
    /// <summary>
    /// Каким ядром раскладывать тело на выпуклые части.
    ///
    /// Own — своё воксельное разложение с метками костей. Части не пересекают
    /// суставы по построению, и работа всегда ограничена бюджетом вокселей и
    /// временем, поэтому редактор не замораживается. По умолчанию — оно.
    ///
    /// Native — нативное V-HACD. Форму режет чуть аккуратнее, но синхронно и
    /// без встроенных пределов: на полном теле это те самые «минуты и
    /// зависание». Оставлено для тех, кому важна именно форма.
    /// </summary>
    public enum DycDecomposeKernel
    {
        Own = 0,
        Native = 1
    }

    /// <summary>
    /// Настройки разложения на выпуклые части.
    ///
    /// Отдельный тип, а не голый struct из ядра, по двум причинам:
    ///   · значения по умолчанию у V-HACD рассчитаны на «один объект за раз»
    ///     (разрешение 100000, до 1024 частей) — для персонажа это минуты
    ///     счёта и сотни коллайдеров, поэтому здесь свои, мобильные;
    ///   · настройки сериализуются в компонент, а сырой struct с указателями
    ///     сериализовать нельзя.
    /// </summary>
    [Serializable]
    public struct DycDecomposeSettings
    {
        /// <summary>
        /// Сторона вокселя в МИЛЛИМЕТРАХ — главный параметр точности.
        ///
        /// Раньше здесь было «разрешение» — абсолютное число вокселей на всё
        /// тело. Это неверная величина: 200 тысяч вокселей, растянутые на
        /// фигуру в 1.8 м, дают воксель 12 мм, а на кисть в 0.2 м — уже 1.4 мм,
        /// то есть в девять раз точнее. Одно и то же число означало разную
        /// точность для разных частей, и мелкие части (пальцы, уши) всегда
        /// оказывались недообсчитанными.
        ///
        /// Размер вокселя одинаков для всего тела, поэтому «5 мм» означает
        /// ровно 5 мм и для бедра, и для фаланги. Число вокселей ядро считает
        /// само из габаритов меша.
        /// </summary>
        [Range(1f, 100f)]
        [Tooltip("Сторона вокселя, мм. Меньше — точнее и намного медленнее. Для персонажа 4-10 мм.")]
        public float voxelSizeMm;

        /// <summary>
        /// Минимальная глубина впадины, при которой ядро продолжает резать, в
        /// ВОКСЕЛЯХ.
        ///
        /// Тоже физическая величина, а не доля: «впадина меньше четырёх
        /// вокселей не считается впадиной». Доля от объёма тела не годится —
        /// 0.8% на груди это 15 см³ (впадину подмышки не тронет), а на пальце
        /// те же 0.8% ничтожны и резать заставляет лишнее.
        /// </summary>
        [Range(1, 32)]
        [Tooltip("Минимальная глубина впадины в вокселях. Меньше — агрессивнее режет.")]
        public int minConcavityVoxels;

        [Range(1, 256)]
        [Tooltip("Предел числа частей на одно тело. Прямо определяет число коллайдеров, то есть стоимость широкой фазы.")]
        public int maxHulls;

        [Range(4, 255)]
        [Tooltip("Предел вершин на часть. 255 — жёсткий лимит PhysX на выпуклую сетку.")]
        public int maxVerticesPerHull;

        [Range(0f, 0.05f)]
        [Tooltip("Части меньше этого объёма отбрасываются. Убирает мусорные осколки в углах.")]
        public float minVolumePerHull;

        [Tooltip("Проецировать вершины частей обратно на поверхность меша. Заметно улучшает прилегание, но может дать мелкие щели.")]
        public bool projectHullVertices;

        /// <summary>
        /// Раздвигать прижатые части тела перед разложением.
        ///
        /// Без этого руки, опущенные вдоль туловища, и сведённые ноги в
        /// воксельной модели сливаются в один объём, и ядро выдаёт одну часть
        /// на две конечности. Зазор заставляет его резать по границе.
        /// </summary>
        [Tooltip("Раздвигать прижатые друг к другу части тела перед разложением. Лечит слипание рук и ног.")]
        public bool separateByBones;

        [Range(0.2f, 10f)]
        [Tooltip("Величина зазора, мм. Больше — ядро охотнее режет по границе, но сильнее искажает форму.")]
        public float separationMm;

        [Tooltip("Нормализовать меш перед разложением (PCA). Помогает на вытянутых телах.")]
        public bool normalize;

        // ------------------------------------------------------------------ своё ядро
        //
        // Поля ниже читает только собственное воксельное разложение. Они все с
        // безопасными значениями по умолчанию: старые компоненты, сохранённые
        // до их появления, десериализуются нулями, и код обязан трактовать
        // ноль как «взять разумное значение», а не как «выключено».

        /// <summary>Каким ядром раскладывать. Ноль (Own) — и для старых компонентов тоже.</summary>
        public DycDecomposeKernel kernel;

        /// <summary>
        /// Предел воксельной сетки. Главный предохранитель от «зависло»: если
        /// заданный размер вокселя даёт больше ячеек, шаг автоматически
        /// укрупняется. Точность падает предсказуемо, редактор — не падает.
        /// </summary>
        [Range(32000, 4000000)]
        [Tooltip("Предел числа вокселей. Больше — точнее и дольше. 1.5 млн — секунды на персонаже.")]
        public int maxVoxels;

        /// <summary>
        /// Насколько «наполненной» должна быть выпуклая оболочка части, чтобы
        /// деление остановилось. 1.0 — идеально выпуклая, 0.6 — резать дальше
        /// почти бессмысленно. Это и есть аналог «вогнутости» V-HACD, только
        /// безразмерный и понятный.
        /// </summary>
        [Range(0.4f, 0.98f)]
        [Tooltip("Требуемая заполненность части. Больше — сильнее дробит, точнее и дороже.")]
        public float convexFillRatio;

        /// <summary>Максимальная глубина рекурсивного деления одной компоненты.</summary>
        [Range(1, 8)]
        [Tooltip("Максимальная глубина деления. Больше — точнее впадины, дороже.")]
        public int maxSplitDepth;

        /// <summary>
        /// Веса костей ниже этого порога не участвуют в голосовании за метку
        /// вокселя. Поднятие порога делает границу между костями резче (плечо
        /// перестаёт «заглатывать» руку), но на сглаженных стыках может
        /// оставить воксели без голосов — их потом добирает распространение
        /// метки по объёму.
        /// </summary>
        [Range(0f, 0.6f)]
        [Tooltip("Порог веса кости при разметке вокселей. Больше — резче границы между костями.")]
        public float boneWeightThreshold;

        /// <summary>
        /// Бюджет времени на разложение, секунды. По истечении разложение
        /// возвращает уже готовые части, а не продолжает считать. 0 — без
        /// предела (не рекомендуется: именно так редактор и вешается).
        /// </summary>
        [Range(0f, 300f)]
        [Tooltip("Бюджет времени разложения, с. 0 — без предела. 20 с хватает персонажу.")]
        public float timeBudgetSeconds;

        /// <summary>
        /// Эффективный бюджет времени. Ноль (а так выглядят компоненты,
        /// сохранённые до появления поля) трактуется как 20 секунд: «без
        /// предела» — это ровно то состояние, в котором редактор и вешался,
        /// поэтому по умолчанию предел есть.
        /// </summary>
        public float EffectiveTimeBudgetSeconds => timeBudgetSeconds > 0f ? timeBudgetSeconds : 20f;

        /// <summary>Значения по умолчанию для персонажа: не «как можно точнее», а «успеть посчитать».</summary>
        public static DycDecomposeSettings Default
        {
            get
            {
                return new DycDecomposeSettings
                {
                    // Подобрано по живой персонажке: воксель 8 мм — это тот
                    // размер, при котором впадины подмышек и паха уже
                    // различимы, а счёт остаётся десятками секунд.
                    voxelSizeMm = 8f,
                    minConcavityVoxels = 8,
                    maxHulls = 64,
                    maxVerticesPerHull = 64,
                    minVolumePerHull = 0.0005f,
                    projectHullVertices = true,
                    separateByBones = true,
                    separationMm = 2f,
                    normalize = false,

                    // Своё ядро по умолчанию: оно не блокирует редактор и не
                    // пересекает суставы. Бюджет 1.5 млн вокселей на персонаже
                    // даёт воксель ~10-12 мм — впадины подмышек и паха уже
                    // различимы, а счёт занимает секунды.
                    kernel = DycDecomposeKernel.Own,
                    maxVoxels = 1500000,
                    // 0.80, а не 0.72. Порог требует, чтобы оболочка части была
                    // заполнена на 80%: всё, что вогнутее, делится дальше. Это
                    // прямая дорога к высокому качеству — лучше больше
                    // мелких выпуклых частей, чем одна большая, съедающая
                    // впадину подмышки или паха.
                    convexFillRatio = 0.80f,
                    maxSplitDepth = 5,
                    boneWeightThreshold = 0.15f,
                    timeBudgetSeconds = 20f
                };
            }
        }
    }
}
