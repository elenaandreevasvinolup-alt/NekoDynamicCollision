using System;
using System.Collections.Generic;
using UnityEngine;

namespace NekoDynamicCollision
{
    /// <summary>
    /// Ручной бюджет частей на одну кость.
    ///
    /// Ключ — ПУТЬ кости, а не индекс. Индекс сломается при любой правке
    /// скелета (переименовали, вставили промежуточную кость, пересобрали префаб),
    /// а путь переживёт всё это. Тот же приём, что у оболочек в DycBakedHull.
    ///
    /// locked означает «не трогать при пересчёте рекомендаций»: пользователь
    /// выставил число осознанно, и автоматика не должна его перезаписывать.
    /// </summary>
    [Serializable]
    public class DycBoneBudget
    {
        public string bonePath;
        public int pieces = 4;
        public bool locked;
    }

    /// <summary>
    /// Что получилось на одной кости при запекании.
    ///
    /// Хранится в наборе, а не считается окном на лету: вогнутость требует
    /// объёма оболочки, то есть повторного счёта, а окно перерисовывается
    /// десятки раз в секунду. Запекание уже знает эти числа — оно их и
    /// записывает.
    /// </summary>
    [Serializable]
    public class DycBoneStat
    {
        public string bonePath;
        public string boneName;

        /// <summary>Треугольников, приписанных кости.</summary>
        public int triangles;

        /// <summary>Сколько частей в итоге осталось после бюджета.</summary>
        public int pieces;

        /// <summary>Сколько частей отброшено бюджетом.</summary>
        public int dropped;

        /// <summary>
        /// Вогнутость 0..1: 1 − объём(тело кости) / объём(её выпуклой оболочки).
        /// Ноль означает «кость почти выпуклая, одной части достаточно»,
        /// единица — «сильно вогнутая, нужен набор частей».
        ///
        /// Это и есть объяснение рекомендации: пользователь видит не магическое
        /// число, а измеренную причину.
        /// </summary>
        public float concavity;

        /// <summary>Объём частей кости, м³. Нужен для оценки покрытия.</summary>
        public float volume;
    }
}
