using System;
using System.Collections.Generic;
using UnityEngine;

namespace NekoDynamicCollision
{
    /// <summary>
    /// Одна запечённая выпуклая оболочка. Вершины mesh лежат в «локальном пространстве трансформа крепления»:
    /// в режиме Skin — локальное пространство кости (вершина = bindposes[boneIndex] * v_mesh),
    /// в режиме Mesh — локальное пространство исходного объекта. В рантайме достаточно создать identity-дочерний объект.
    /// </summary>
    [Serializable]
    public class DycBakedHull
    {
        public Mesh mesh;

        public int elementIndex;
        public int groupIndex;

        /// <summary>Иерархический путь относительно корня компонента. Пусто = висит на самом компоненте (режим Mesh).</summary>
        public string bonePath;

        /// <summary>
        /// Мягкий режим: номер кластера деформации. -1 — обычная оболочка,
        /// которая крепится по bonePath. Иначе оболочка крепится к кадру,
        /// который каждый кадр пишет Dyc_DeformDriver, и bonePath не нужен.
        ///
        /// Номер — это ИНДЕКС, а не ссылка: он связывает запечённую оболочку с
        /// кадром из источника деформации, поэтому число кадров и число
        /// кластеров обязано совпадать (проверяется здоровьем и двигателем).
        /// </summary>
        public int clusterIndex = -1;

        /// <summary>
        /// Мягкий режим: кость, к которой привязан кластер.
        ///
        /// Зачем это здесь, если у мягкого тела есть решатель. Решатель
        /// необязателен: без него NDC обязан сам вести кадры кластеров, а
        /// единственное, за чем может следовать кластер без симуляции, — это
        /// его кость. Тогда оболочки повторяют РЕАЛЬНУЮ позу скелета (пусть и
        /// жёстко в пределах кластера), а не остаются в rest-позе. Пусто — у
        /// кластера кости нет (мягкое тело без скелета): он едет с объектом.
        /// </summary>
        public string clusterBonePath;

        /// <summary>
        /// Поза покоя кадра мягкого кластера, в пространстве владельца.
        ///
        /// Мягкое тело — это НЕ скелет: деформацию приносит решатель или код.
        /// Пока источника нет, кадр обязан стоять там, где кластер был в меше,
        /// иначе оболочки соберутся в одну точку. Смещение хранится здесь, и
        /// двигатель ставит кадр по нему при создании.
        ///
        /// Оболочка кластера построена ОТНОСИТЕЛЬНО этой точки, поэтому
        /// движок может свободно вращать кадр — форма повернётся целиком.
        /// </summary>
        public Vector3 clusterRest;

        /// <summary>
        /// Индексы вершин ИСХОДНОГО меша, из которых построена оболочка.
        ///
        /// Нужны «живому» обновлению: оно
        /// берёт текущую позу скелета, снова сэмплирует эти вершины и
        /// пересобирает оболочку. Без списка вершин оболочка могла бы только
        /// жёстко ехать за костью, но не следовать деформации.
        ///
        /// Пусто у запеканий до появления поля — такие оболочки остаются
        /// статичными, и это не ошибка.
        /// </summary>
        public int[] sourceVertices;

        /// <summary>Номер исходного рендерера в наборе. Нужен, когда у персонажа
        /// несколько мешей: «живое» обновление берёт вершины из своего.</summary>
        public int sourceIndex;

        /// <summary>
        /// Номер материала в <see cref="Dyc_BakedSet.sourceMaterials"/>,
        /// разрешённый при запекании: исходный материал подмеша → физический
        /// материал (по карте материалов или переопределению на кости).
        ///
        /// -1 — не разрешён: материал берётся из группы, как раньше. Так
        /// старые наборы работают без изменений.
        /// </summary>
        public int materialIndex = -1;

        /// <summary>
        /// НЕвыпуклая часть: mesh — кусок исходной поверхности, а не оболочка.
        ///
        /// Рантайм обязан ставить такому коллайдеру convex = false: отправлять
        /// невыпуклую сетку в convex-cooking нельзя, PhysX либо откажет, либо
        /// молча испортит форму. Флаг хранится НА ЧАСТИ, а не только на наборе:
        /// старые запекания (до появления поля) остаются целиком выпуклыми, а
        /// смешанный набор «оболочки + поверхность» не превращается в ошибку.
        /// </summary>
        public bool nonConvex;

        /// <summary>Мировая матрица в bind-позе. Нужна Editor'у для отрисовки выпуклой оболочки в T-pose, не зависит от текущей анимации.</summary>
        public Matrix4x4 bindWorld;

        public Vector3 localCenter;
        public Vector3 localSize;

        /// <summary>Объём выпуклой оболочки, м³. Используется в Auto Mass.</summary>
        public float volume;

        public int vertexCount;
        public int triangleCount;

        /// <summary>Отрезки рёбер после дедупликации (с объединением компланарных), хранятся парами: 0-1, 2-3, 4-5… Для Editor-гизмо.</summary>
        public Vector3[] edges;

        /// <summary>
        /// Нормали граней, смежных с каждым ребром (по две на ребро). Гизмо
        /// отсекает по ним рёбра, повёрнутые от камеры, — так невидимая сторона
        /// оболочки не рисуется. У запеканий до появления поля массив пуст, и
        /// гизмо просто рисует все рёбра.
        /// </summary>
        public Vector3[] edgeNormals;
    }

    /// <summary>
    /// Результат запекания. Только ссылки на ассеты + чистые данные: в рантайме лишь загрузка, без вычислений.
    /// </summary>
    public class Dyc_BakedSet : ScriptableObject
    {
        public string sourceHash;

        /// <summary>
        /// Путь объекта-владельца («Сцена:/Корень/Таз»), снятый при запекании.
        ///
        /// Нужен только для одного: два объекта с ОДИНАКОВЫМ именем (обычное
        /// дело для префаб-инстансов) раньше писали в один и тот же ассет, и
        /// второй молча затирал первый. По этому полю ассет узнаёт «свой» объект
        /// и при чужом имени получает свободное.
        /// </summary>
        public string sourcePath;

        /// <summary>
        /// Сработало ли РАЗЛОЖЕНИЕ при запекании, а не запасная кластеризация.
        ///
        /// Хранится в наборе, а не только в отчёте: отчёт живёт до следующего
        /// запекания, а вопрос «нарезано по впадинам или затянуто оболочкой»
        /// возникает и через неделю. Это же число отделяет результат от
        /// одной затягивающей оболочки системного коллайдера.
        /// </summary>
        public bool decomposed;

        public int sourceVertexCount;
        public int sourceTriangleCount;
        public int sourceSubMeshCount;

        public DycMode mode;
        public DycPrecision precision;
        public float seamOverlap;
        public float boneWeightThreshold;

        /// <summary>
        /// Форма, которой запекались коллайдеры. Хранится в наборе, потому что
        /// от неё зависят проверки здоровья и предпросмотр: у невыпуклого набора
        /// потолок вершин PhysX (255) не действует, зато действуют ограничения
        /// на Rigidbody и масштаб.
        /// </summary>
        public DycColliderShape colliderShape = DycColliderShape.Convex;

        /// <summary>
        /// Мягкий режим: сколько кластеров деформации было при запекании.
        /// Источник кадров обязан вернуть ровно столько же; расхождение
        /// означает, что топология мягкого тела изменилась и нужна перезапечка.
        /// 0 — обычный режим.
        /// </summary>
        public int clusterCount;

        /// <summary>Отпечаток топологии мягкого тела на момент запекания.
        /// Сравнивается с тем, что отдаёт источник кадров.</summary>
        public int softTopologyStamp;

        /// <summary>Карта контактов для упрощённой самоколлизии (ядро Synapse). Может быть null.</summary>
        public Dyc_ContactMap contactMap;

        /// <summary>
        /// Что получилось на каждой кости: треугольники, части, вогнутость.
        ///
        /// Заполняется запеканием и читается окном эксперта. Считать это в окне
        /// нельзя: вогнутость требует объёма оболочки, а окно перерисовывается
        /// много раз в секунду.
        /// </summary>
        public List<DycBoneStat> boneStats = new List<DycBoneStat>();

        public List<DycBakedHull> hulls = new List<DycBakedHull>();

        /// <summary>
        /// Физический материал на каждую группу, УЖЕ разрешённый при запекании
        /// (с учётом карты материалов и переопределений на костях).
        ///
        /// Пусто — материал берётся из списка групп компонента, как раньше.
        /// Так старые наборы работают без изменений, а новые не зависят от
        /// того, что сейчас лежит в компоненте.
        /// </summary>
        public List<PhysicMaterial> groupMaterials = new List<PhysicMaterial>();

        /// <summary>
        /// Разрешённые физические материалы по материалам исходных мешей:
        /// сначала материалы первого источника по порядку подмешей, затем
        /// второго и так далее. Сюда же попадают переопределения с костей.
        ///
        /// Отдельно от <see cref="groupMaterials"/>, потому что отвечает на
        /// другой вопрос: «какой материал у ЭТОЙ оболочки по её исходному
        /// материалу», а не «какой материал у зоны».
        /// </summary>
        public List<PhysicMaterial> sourceMaterials = new List<PhysicMaterial>();

        /// <summary>Число треугольников без принадлежности к разделу (для диагностики).</summary>
        public int unassignedTriangles;
        /// <summary>Число кластеров, вырожденных до невозможности построить выпуклую оболочку (для диагностики).</summary>
        public int degenerateClusters;
        /// <summary>Метка времени запекания (UTC ticks).</summary>
        public long generatedUtcTicks;

        /// <summary>Снимок bindposes исходного меша на момент запекания, только для диагностики в Editor.</summary>
        public List<Matrix4x4> bindPoses = new List<Matrix4x4>();
        /// <summary>Пути костей, соответствующие bindposes; взаимно однозначно с bindPoses.</summary>
        public List<string> bindBonePaths = new List<string>();

        /// <summary>Мировая матрица корневой кости в bind-позе. Гизмо использует её, чтобы выровнять bind-позу по текущему положению персонажа.</summary>
        public Matrix4x4 bindRootWorld;
        /// <summary>Путь корневой кости.</summary>
        public string bindRootBonePath;

        public int TotalVertexCount
        {
            get
            {
                int n = 0;
                for (int i = 0; i < hulls.Count; i++)
                    if (hulls[i] != null) n += hulls[i].vertexCount;
                return n;
            }
        }

        public int TotalTriangleCount
        {
            get
            {
                int n = 0;
                for (int i = 0; i < hulls.Count; i++)
                    if (hulls[i] != null) n += hulls[i].triangleCount;
                return n;
            }
        }

        public float TotalVolume
        {
            get
            {
                float v = 0f;
                for (int i = 0; i < hulls.Count; i++)
                    if (hulls[i] != null) v += hulls[i].volume;
                return v;
            }
        }

        public int MaxHullVertices
        {
            get
            {
                int m = 0;
                for (int i = 0; i < hulls.Count; i++)
                    if (hulls[i] != null && hulls[i].vertexCount > m) m = hulls[i].vertexCount;
                return m;
            }
        }
    }
}
