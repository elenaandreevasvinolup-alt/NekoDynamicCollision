using UnityEditor;

namespace NekoDynamicCollision.EditorTools
{
    /// <summary>
    /// Режим инспектора: простой или экспертный.
    ///
    /// ЧТО ЭТО МЕНЯЕТ. Только то, ЧТО ВИДНО СРАЗУ — и ничего больше. В простом
    /// режиме развёрнуты четыре контрола, которых хватает, чтобы запечь
    /// персонажа и пойти играть; всё остальное свёрнуто, но НЕ ВЫКЛЮЧЕНО и не
    /// спрятано. В экспертном всё раскрыто и показывает техническую сторону:
    /// бюджеты, ядро разложения, переопределения по костям.
    ///
    /// ПОЧЕМУ НЕ ДВА РАЗНЫХ ИНСПЕКТОРА. Раздельные экраны пришлось бы держать
    /// в согласии: новая настройка должна появиться в обоих, и рано или поздно
    /// один отстал бы. Здесь один экран и один переключатель раскрытия —
    /// расхождение невозможно по построению.
    ///
    /// Настройка общая для редактора, а не для компонента: это привычка
    /// человека, а не свойство персонажа. Один раз включив экспертный режим,
    /// его не хочется включать заново на каждом объекте.
    /// </summary>
    public static class Dyc_Expert
    {
        const string PrefKey = "Neko.DynamicCollision.ExpertMode";

        /// <summary>Экспертный режим включён. Хранится в EditorPrefs.</summary>
        public static bool Enabled
        {
            get { return EditorPrefs.GetBool(PrefKey, false); }
            set { EditorPrefs.SetBool(PrefKey, value); }
        }
    }
}
